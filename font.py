ACUTE = ('...#.', '..#..')
UML = (E, '.#.#.')
DACUTE = ('..#.#', '.#.#.')
LOWER_ACC = {'á': ('a', ACUTE), 'é': ('e', ACUTE), 'ó': ('o', ACUTE), 'ú': ('u', ACUTE),
             'ö': ('o', UML), 'ü': ('u', UML), 'ő': ('o', DACUTE), 'ű': ('u', DACUTE)}
UPPER_ACC = {'Á': ('A', ACUTE), 'É': ('E', ACUTE), 'Í': ('I', ACUTE), 'Ó': ('O', ACUTE),
             'Ú': ('U', ACUTE), 'Ö': ('O', UML), 'Ü': ('U', UML), 'Ő': ('O', DACUTE), 'Ű': ('U', DACUTE)}

def cell(ch):
    """10 sor x 8 bit (bit7 = bal szélső pont)"""
    rows = [E] * 10
    if ch in UPPER_ACC:
        base, acc = UPPER_ACC[ch]
        rows[2:10] = G[base]; rows[0:2] = acc
    elif ch in LOWER_ACC:
        base, acc = LOWER_ACC[ch]
        rows[2:10] = G[base]; rows[2:4] = acc
    elif ch == 'í':
        rows[2:10] = G['i']; rows[2:4] = ACUTE
    else:
        rows[2:10] = G[ch]
    # ékezetsorok: ezeket nem vastagítjuk (különben a két vessző összefolyna)
    acc_rows = set()
    if ch in UPPER_ACC: acc_rows = {0, 1}
    elif ch in LOWER_ACC or ch == 'í': acc_rows = {2, 3}
    out = []
    for y, r in enumerate(rows):
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= 0x40 >> i        # 1..5. oszlop
                # megvastagítás +1 oszloppal jobbra, de az egypontos rés megmarad (m, w, M, ...)
                if y not in acc_rows and not (i + 2 < 5 and r[i + 2] == '#' and r[i + 1] == '.'):
                    v |= 0x20 >> i
        out.append(v)
    return out

def preview(text, path, scale=(2, 3.2)):
    from PIL import Image
    import numpy as np
    w = 8 * len(text)
    a = np.zeros((10, w), bool)
    for i, ch in enumerate(text):
        for y, v in enumerate(cell(ch)):
            for x in range(8):
                a[y, i * 8 + x] = (v >> (7 - x)) & 1
    im = Image.fromarray(np.where(a, 0, 255).astype('uint8'))
    im.resize((int(w * scale[0] * 2), int(10 * scale[1] * 2)), Image.NEAREST).save(path)

